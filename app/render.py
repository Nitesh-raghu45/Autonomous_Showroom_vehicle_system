"""Response templates. Pure functions: record/data in, customer-facing text out.

Facts (dates, totals, ids) are formatted here in Python - never generated by a model.
"""
from __future__ import annotations

import re

from datetime import date, datetime
from typing import Any

SCOPE_LINE = "I can help with your details, enquiry, quotation, contact history, appointments and our vehicle stock."

STATUS_MEANING = {
    "open": "it's still open and being worked on",
    "closed_won": "it closed as won - the deal went through",
    "closed_lost": "it closed as lost - no sale resulted",
}
TYPE_LABEL = {
    "TEST_DRIVE": "Test drive", "CALLBACK": "Callback", "ADVANCE_PAYMENT": "Advance payment",
    "DOCUMENT_SUBMISSION": "Document submission", "OTHER": "Appointment",
}


def d(value: Any) -> str:
    if not value:
        return "not set"
    s = str(value)
    return s.split("T")[0]


def money(v: Any) -> str:
    try:
        return f"INR {float(v):,.2f}"
    except (TypeError, ValueError):
        return "n/a"


def lakh(v: int) -> str:
    return f"₹{v / 100000:.2f}L"


def _veh(make: Any, model: Any) -> str:
    return f"{make or ''} {model or ''}".strip()


def _salesperson_name(value: Any) -> str:
    name = str(value or "").strip()
    if re.fullmatch(r"[A-Za-z]+[._][A-Za-z]+", name):
        return " ".join(part.capitalize() for part in re.split(r"[._]", name))
    return name


