def _quote_totals(q: dict[str, Any]) -> tuple[float, float]:
    b = q.get("cost_breakdown") or []
    return (sum(float(i.get("sale_amount") or 0) for i in b), sum(float(i.get("vat_amount") or 0) for i in b))


def field_line(field: str, rec: dict[str, Any], today: date, slots: dict[str, Any] | None = None) -> str:
    c = rec.get("customer") or {}
    e = rec.get("enquiry") or {}
    q = rec.get("quotation")
    slots = slots or {}

    if field == "email":
        return f"Your registered email is {c['email']}." if c.get("email") else "There's no email on your record."
    if field == "mobile":
        return f"The mobile number on file is {c.get('mobile_no')}."
    if field == "alt_mobile":
        return f"Your alternate mobile number is {c['alt_mobile_no']}." if c.get("alt_mobile_no") else "There's no alternate mobile number on your record."
    if field == "customer_id":
        return f"Your customer ID is {c.get('customer_id')}."
    if field == "name":
        return f"The name on your record is {c.get('title', '')} {c.get('name', '')}.".replace("  ", " ")
    if field == "salesperson":
        return f"Your enquiry is being handled by {_salesperson_name(e['salesperson'])}." if e.get("salesperson") else "No salesperson has been assigned to your enquiry yet."
    if field == "enquiry_id":
        return f"Your enquiry ID is {e.get('enquiry_id')}." if e.get("enquiry_id") else "There's no enquiry on your record."
    if field == "status":
        st = e.get("status")
        if not st:
            return "There's no enquiry status on your record."
        return f"Your enquiry status is '{st}' - {STATUS_MEANING.get(st, 'that is the status on record')}."
    if field == "why_status":
        if slots.get("q") and q:
            return f"Your quotation {q.get('proposal_id')} is '{q.get('status')}', but the record doesn't say why."
        st = e.get("status")
        return f"Your enquiry is '{st}', but the record doesn't include a reason." if st else "There's no enquiry status on your record."
    if field.startswith("status_meaning:"):
        term = field.split(":", 1)[1]
        mean = STATUS_MEANING.get(term)
        st = e.get("status")
        cur = f" Your enquiry is currently '{st}'." if st else ""
        return (f"'{term}' means {mean}." if mean else "That status isn't defined in my reference list.") + cur
    if field == "q_summary":
        if not q:
            return "No quotation has been raised for you yet."
        sale, vat = _quote_totals(q)
        v = q.get("vehicle") or {}
        return (f"Quotation {q.get('proposal_id')} for the {_veh(v.get('make'), v.get('model'))}: status '{q.get('status')}', "
                f"total {money(sale + vat)} ({money(sale)} + {money(vat)} tax), delivery {d(q.get('delivery_date')) if q.get('delivery_date') else 'date not set'}.")
    if field == "created":
        return f"Your enquiry was raised on {d(e.get('created_at'))}."
    if field == "age":
        try:
            raised = date.fromisoformat(d(e.get("created_at")))
            n = (today - raised).days
            return f"You raised your enquiry {n} day{'s' if n != 1 else ''} ago (on {raised.isoformat()})."
        except ValueError:
            return "The record has no enquiry date."
    if field == "new_or_used":
        return f"Your enquiry is for a {e['new_or_used']} vehicle." if e.get("new_or_used") else "The record doesn't say whether you want a new or used vehicle."
    if field == "vehicle":
        v = _veh(e.get("interested_make"), e.get("interested_model"))
        return f"You enquired about the {v}." if v else "The record doesn't list a vehicle you're interested in."
    if field == "enq_summary":
        if not e:
            return "There's no enquiry on your record."
        v = _veh(e.get("interested_make"), e.get("interested_model")) or "no vehicle listed"
        return (f"Enquiry {e.get('enquiry_id')}: {v} ({e.get('new_or_used') or 'new/used not set'}), status '{e.get('status')}', "
                f"raised {d(e.get('created_at'))}, handled by {_salesperson_name(e.get('salesperson')) or 'no one yet'}.")

    # ---- quotation fields ----
    if field in ("proposal_id", "q_status", "delivery", "delivery_delivered", "stock_id", "q_vehicle", "breakdown",
                 "sale_total", "tax_total", "grand_total"):
        if not q:
            return "No quotation has been raised for you yet."
        sale, vat = _quote_totals(q)
        veh = q.get("vehicle") or {}
        if field == "proposal_id":
            return f"Your proposal ID is {q.get('proposal_id')}."
        if field == "q_status":
            return f"Your quotation {q.get('proposal_id')} is '{q.get('status')}'."
        if field == "delivery":
            return f"The expected delivery date is {d(q.get('delivery_date'))}." if q.get("delivery_date") else "There's no delivery date on your quotation yet."
        if field == "delivery_delivered":
            return f"The record shows an expected delivery date of {d(q.get('delivery_date'))}; it doesn't say whether it has been delivered."
        if field == "stock_id":
            return f"The stock ID on your quotation is {veh.get('stock_id')}."
        if field == "q_vehicle":
            return f"Your quotation is for the {_veh(veh.get('make'), veh.get('model'))}."
        if field == "sale_total":
            return f"The sale amount before tax is {money(sale)}."
        if field == "tax_total":
            return f"The tax included in your quotation is {money(vat)}."
        if field == "grand_total":
            return f"Your grand total is {money(sale + vat)} ({money(sale)} sale + {money(vat)} tax)."
        if field == "breakdown":
            lines = [f"- {i.get('description', 'item')}: sale {money(i.get('sale_amount'))}, tax {money(i.get('vat_amount'))}"
                     for i in (q.get("cost_breakdown") or [])]
            return "Cost breakdown:\n" + "\n".join(lines) + f"\nTotal: {money(sale)} + {money(vat)} tax = {money(sale + vat)}."
    return ""


def fields_answer(fields: list[str], rec: dict[str, Any], today: date, slots: dict[str, Any] | None = None) -> str:
    if fields == ["profile_summary"]:
        c = rec.get("customer") or {}
        parts = [f"{c.get('title', '')} {c.get('name', '')}".strip() + f" (ID {c.get('customer_id')})",
                 f"Mobile {c.get('mobile_no')}" + (f", alt {c['alt_mobile_no']}" if c.get("alt_mobile_no") else ""),
                 f"Email {c.get('email')}"]
        return "Here are your details:\n- " + "\n- ".join(parts) + "\n- " + field_line("enq_summary", rec, today)
    lines = [field_line(f, rec, today, slots) for f in fields]
    lines = [x for x in lines if x]
    if len(lines) == 1:
        return lines[0]
    return "\n".join("- " + x if "\n" not in x else x for x in lines)


def contact_answer(rec: dict[str, Any], slots: dict[str, Any]) -> str:
    logs = sorted(rec.get("contact_log") or [], key=lambda x: str(x.get("log_date") or ""))
    pre = "I don't have call transcripts - only the notes that were logged. " if slots.get("transcript") else ""
    ct = slots.get("ctype")
    if ct and logs and slots.get("mode") == "last":
        typed = [x for x in logs if x.get("contact_type") == ct]
        if not typed:
            last = logs[-1]
            return pre + f"No {ct.replace('_', ' ').lower()} is logged for you. Your last contact was on {d(last.get('log_date'))} via {last.get('contact_type')}: {last.get('notes', 'no notes')}"
        logs = typed
    if not logs:
        return pre + "No contact has been logged for your enquiry yet."
    mode = slots.get("mode")
    if mode == "count":
        return pre + f"We've logged {len(logs)} contact{'s' if len(logs) != 1 else ''} with you so far."
    if mode == "all":
        return pre + f"Your contact history ({len(logs)}):\n" + "\n".join(
            f"- {d(x.get('log_date'))} | {x.get('contact_type')} | {x.get('notes', 'no notes')}" for x in logs)
    last = logs[-1]
    want = slots.get("want")
    if want == "type":
        return pre + f"You were last contacted via {last.get('contact_type')} on {d(last.get('log_date'))}."
    if want == "date":
        return pre + f"Your last contact was on {d(last.get('log_date'))} ({last.get('contact_type')})."
    return pre + f"Your last contact was on {d(last.get('log_date'))} via {last.get('contact_type')}: {last.get('notes', 'no notes')}"


def appointments_answer(rec: dict[str, Any], appts: list[dict[str, Any]], cap: int = 8) -> str:
    entries: list[tuple[int, str, str, str]] = []          # (rank, date, time, text)
    s = rec.get("scheduled_contact")
    if s:
        hh, mm = s.get("sched_hour"), s.get("sched_minute")
        t = f"{hh:02d}:{mm:02d}" if isinstance(hh, int) and isinstance(mm, int) else "time not set"
        rank = 0 if s.get("status") in ("pending", "confirmed") else 1
        entries.append((rank, d(s.get("sched_date")), t, f"- {s.get('contact_type') or 'Contact'} on {d(s.get('sched_date'))} at {t} - {s.get('status')} (arranged by the dealership)"))
    for a in appts:
        rank = 0 if a.get("status") == "confirmed" else 1
        entries.append((rank, str(a.get("date")), str(a.get("time")),
                        f"- {TYPE_LABEL.get(a.get('appointment_type'), 'Appointment')} on {a.get('date')} at {a.get('time')} - {a.get('status')} (ID {a.get('appointment_id')})"))
    if not entries:
        return "You don't have any appointments scheduled."
    entries.sort(key=lambda e: (e[0], e[1], e[2]))
    active = sum(1 for e in entries if e[0] == 0)
    shown = entries[:cap]
    head = f"You have {active} upcoming appointment{'s' if active != 1 else ''}" + (f" and {len(entries) - active} past/cancelled" if len(entries) > active else "") + ":"
    more = f"\n…and {len(entries) - cap} more (past or cancelled)." if len(entries) > cap else ""
    return head + "\n" + "\n".join(e[3] for e in shown) + more


