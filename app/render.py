def not_in_record(topic: str | None = None) -> str:
    low_topic = (topic or "").lower()
    if any(w in low_topic for w in ("quot", "price", "proposal", "cost")):
        return (
            "No quotation has been generated for your enquiry yet. "
            "💡 **Here's what I can help with instead:**\n"
            "• Check your **enquiry status** and details\n"
            "• Browse our **inventory** and find the right vehicle\n"
            "• **Book a test drive** to experience the car firsthand\n"
            "• Ask your salesperson to prepare a quotation for you\n\n"
            "Would you like to do any of these?"
        )
    if any(w in low_topic for w in ("deliver", "car ready")):
        return (
            "There's no delivery date on your record yet. "
            "💡 Once your quotation is finalized, the delivery timeline will be updated. "
            "Would you like to check your **enquiry status** or **quotation details** instead?"
        )
    return "That isn't on your record, so I can't say. " + SCOPE_LINE


def refuse(kind: str) -> str:
    if kind in ("other_customer", "bulk_data"):
        return "I can only discuss your own account, not other customers' information. " + SCOPE_LINE
    if kind in ("prompt_leak", "system_disclosure", "impersonation"):
        return "I can't help with that. " + SCOPE_LINE
    return "That's outside what I can help with here. " + SCOPE_LINE


_COMPLIMENT_RE = re.compile(r"^(ok(ay)?[, ]+)?(you'?re?|you are|this is|that'?s?|that is)\s+(doing (well|good|great)|(working (really |very )?(well|good|great|perfect(ly)?)|(really |very )?(good|great|helpful|awesome|amazing|nice|useful|fast|quick)))\W*$|^(good|great|nice|well done|awesome) (job|work|bot)\W*$")
_COMPLIMENT_EXPECTATION_RE = re.compile(r"^(?:this is|that is|that's) (?:exactly )?what i (?:was )?(?:expecting|expected)(?: from you)?\W*$")


def greeting(low: str) -> str:
    if low in ("help", "menu", "options") or low.startswith(("what can", "what do you", "who are", "what are", "are you", "how can")):
        return "I'm the dealership's customer assistant - an automated bot, not a person. " + SCOPE_LINE
    if low.rstrip("!. ") in ("ok", "okay", "fine", "cool", "alright", "got it", "k", "nice", "great", "good", "no", "nope", "nah", "nothing", "nothing special", "that's all", "that is all"):
        return "Alright - let me know if there's anything else I can help with."
    if low.startswith("thank"):
        return "You're welcome! Anything else I can help with?"
    if low.startswith(("bye", "goodbye")):
        return "Goodbye! Have a great day."
    if _COMPLIMENT_RE.match(low) or _COMPLIMENT_EXPECTATION_RE.match(low):
        return "Thank you! Happy to help - is there anything else you'd like to do?"
    return "Hi! " + SCOPE_LINE + " What would you like to do?"


def clarify(kind: str, **kw: Any) -> str:
    if kind == "empty":
        return "What would you like to know? " + SCOPE_LINE
    if kind == "gibberish":
        return "I couldn't understand that message. Please ask about a vehicle, your enquiry, quotation, profile, or an appointment."
    if kind == "inventory_best":
        return "Which criterion should I use to find the best vehicle: lowest price, lowest mileage, family use, fuel type, or budget?"
    if kind == "vehicle_unavailable":
        return f"We don't currently stock the {kw.get('make')} {kw.get('model')}. I can show you the {kw.get('make')} vehicles that are available."
    if kind == "nothing_pending":
        return "There's nothing waiting for your confirmation. What would you like to do?"
    if kind == "human":
        return ("I can't transfer you to a person or log a complaint from this chat, and I don't have the showroom's contact details. "
                "Please contact the dealership directly. I can still help with your enquiry, quotation or appointments.")
    if kind == "reschedule":
        return ("I can't move an appointment in one step: I'll cancel the current one and book a new slot. "
                "Which appointment should I cancel, and what date and time (08:00-20:00) would you like instead?")
    if kind == "multi_booking":
        return "I can book one appointment at a time. Tell me the type, date and time for the first one and I'll set it up, then we can do the next."
    if kind == "already_registered":
        if kw.get("name"):
            return f"You're already registered as {kw['name']} (ID {kw.get('cid')}). To register someone else, please use the New Account form."
        return "It looks like you may already have an account. For your security, please verify with the mobile number on it instead of registering again."
    return "Could you tell me a bit more?"


